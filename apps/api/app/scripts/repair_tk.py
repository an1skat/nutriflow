async def _find_ingredient(name: str) -> Ingredient:
    from app.modules.recipe.service import list_ingredients

    existing, _ = await list_ingredients(offset=0, limit=100, query=name, include_inactive=True)
    norm = " ".join(name.strip().lower().split())
    for item in existing:
        if " ".join(item.name.strip().lower().split()) == norm and item.unit.lower() == "g":
            return item
    from app.modules.recipe.schemas import CreateIngredientRequest
    from app.modules.recipe.service import RecipeConflictError, create_ingredient
    try:
        return await create_ingredient(CreateIngredientRequest(name=name, unit="g", aliases=[]))
    except RecipeConflictError:
        existing, _ = await list_ingredients(offset=0, limit=100, query=name, include_inactive=True)
        for item in existing:
            if " ".join(item.name.strip().lower().split()) == norm and item.unit.lower() == "g":
                return item
        raise


async def repair_card(card_number: str, rows: list[tuple]) -> dict:
    dc = await DishCard.find_one({"card_number": card_number})
    if not dc:
        return {"card": card_number, "status": "no-card"}
    old_version = await DishCardVersion.get(dc.current_version_id) if dc.current_version_id else None
    if not old_version:
        return {"card": card_number, "status": "no-version"}

    # Reuse portion variants from the old version (they were parsed correctly).
    portion_variants: list[PortionVariantPayload] = []
    portion_id_by_output: dict[str, PydanticObjectId] = {}
    for pv in old_version.portion_variants:
        portion_variants.append(
            PortionVariantPayload(
                id=pv.id,
                age_group=pv.age_group,
                portion_grams=pv.portion_grams,
                output_grams=pv.output_grams,
                nutrition=NutritionPayload(
                    kcal=pv.nutrition.kcal,
                    proteins=pv.nutrition.proteins,
                    fats=pv.nutrition.fats,
                    carbs=pv.nutrition.carbs,
                ),
            )
        )
        portion_id_by_output[str(pv.portion_grams)] = pv.id

    ingredient_amounts: list[IngredientAmountPayload] = []
    for name, group, alt, notes, amounts in rows:
        ingredient = await _find_ingredient(name)
        for output_grams, (gross, net) in amounts.items():
            ingredient_amounts.append(
                IngredientAmountPayload(
                    ingredient_id=ingredient.id,
                    ingredient_name_snapshot=name,
                    group_key=group,
                    alternative_label=alt,
                    gross_amount=Decimal(gross),
                    net_amount=Decimal(net),
                    unit="g",
                    portion_variant_id=portion_id_by_output[output_grams],
                    notes=notes,
                )
            )

    new_version = await create_dish_card_version(
        dc.id,
        CreateDishCardVersionRequest(
            technology_text=old_version.technology_text,
            allergen_ids=list(old_version.allergen_ids),
            portion_variants=portion_variants,
            ingredient_amounts=ingredient_amounts,
        ),
        created_by=None,
    )
    validation = await validate_dish_card_version(new_version.id)
    if validation.blocking_errors:
        return {"card": card_number, "status": "blocked", "errors": [f"{e.code}: {e.message}" for e in validation.blocking_errors[:3]]}
    confirmed = await confirm_dish_card_version(new_version.id)

    # Archive the old version so it no longer shadows the new one.
    old_version.status = DishCardVersionStatus.ARCHIVED
    await old_version.save()

    return {"card": card_number, "status": "repaired", "new_version": str(confirmed.id)}


